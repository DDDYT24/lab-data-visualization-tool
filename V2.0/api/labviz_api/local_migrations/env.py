"""Alembic environment for the local SQLite profile schema.

The chain under ``migrations/`` builds the normalized PostgreSQL lineage schema from
``labviz_api.db.models``. The local profile is a different schema, owned by
``labviz_api.repository`` and the research sidecar installers, so it gets its own
revision chain and its own version table. Nothing here is autogenerated: the local
schema has no SQLAlchemy metadata, so every revision is written by hand.
"""

from __future__ import annotations

from logging.config import fileConfig

from alembic import context
from sqlalchemy import create_engine, pool

from labviz_api.local_schema import VERSION_TABLE, require_sqlite_url

config = context.config

if config.config_file_name is not None:
    fileConfig(config.config_file_name)


def database_url() -> str:
    """Prefer a caller-injected URL so the application never depends on a working directory."""
    injected = config.attributes.get("database_url")
    if isinstance(injected, str):
        return injected
    configured = config.get_main_option("sqlalchemy.url")
    if not configured:
        raise RuntimeError("A SQLite URL is required to run the local migrations.")
    return configured


def run_migrations_offline() -> None:
    context.configure(
        url=require_sqlite_url(database_url()),
        literal_binds=True,
        dialect_opts={"paramstyle": "named"},
        version_table=VERSION_TABLE,
        render_as_batch=True,
    )

    with context.begin_transaction():
        context.run_migrations()


def run_migrations_online() -> None:
    connectable = create_engine(require_sqlite_url(database_url()), poolclass=pool.NullPool)
    try:
        with connectable.connect() as connection:
            context.configure(
                connection=connection,
                version_table=VERSION_TABLE,
                render_as_batch=True,
            )

            with context.begin_transaction():
                context.run_migrations()
    finally:
        # Windows keeps a deleted or moved database file locked while any connection
        # survives, which previously broke offline backup and restore.
        connectable.dispose()


if context.is_offline_mode():
    run_migrations_offline()
else:
    run_migrations_online()
